def write_sitemap(urls: Iterable[tuple[str, str | None]]) -> None:
    unique: dict[str, str | None] = {}
    for url, lastmod in urls:
        unique[url] = lastmod
    entries = []
    for url in sorted(unique, key=lambda value: (value != f"{BASE_URL}/", value)):
        lastmod = unique[url]
        lastmod_xml = f"\n    <lastmod>{escape(lastmod)}</lastmod>" if lastmod else ""
        entries.append(f"  <url>\n    <loc>{escape(url)}</loc>{lastmod_xml}\n  </url>")
    xml = '<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n' + "\n".join(entries) + "\n</urlset>\n"
    (ROOT / "sitemap.xml").write_text(xml, encoding="utf-8")


def validate_output(products: list[dict[str, Any]]) -> None:
    checks = [
        INDEX_PATH,
        ROOT / "robots.txt",
        ROOT / "sitemap.xml",
        ROOT / "llms.txt",
        SHOP_DIR / "index.html",
        CARE_DIR / "index.html",
        ROOT / "about.html",
        ROOT / "contact.html",
        ROOT / "shipping.html",
    ]
    missing = [str(path.relative_to(ROOT)) for path in checks if not path.exists()]
    if missing:
        raise RuntimeError(f"Missing generated SEO files: {', '.join(missing)}")
    index = INDEX_PATH.read_text(encoding="utf-8")
    if "SEO-SCHEMA:BEGIN" not in index or "Colorado Reptile Store" not in index:
        raise RuntimeError("index.html does not contain the generated SEO metadata.")
    sitemap = (ROOT / "sitemap.xml").read_text(encoding="utf-8")
    if f"{BASE_URL}/shop/" not in sitemap or f"{BASE_URL}/care-guides/" not in sitemap:
        raise RuntimeError("sitemap.xml is missing key landing pages.")
    if products and not any(PRODUCTS_DIR.glob("*.html")):
        raise RuntimeError("No product pages were generated from a non-empty catalog.")


