def product_schema(product: dict[str, Any]) -> dict[str, Any]:
    name = compact_text(product.get("public_name"), "Website product")
    images = product.get("image_urls") if isinstance(product.get("image_urls"), list) else []
    images = [absolute_url(compact_text(value)) for value in images if compact_text(value)]
    if not images:
        images = [absolute_url(compact_text(product.get("image_url")))]
    data: dict[str, Any] = {
        "@type": "Product",
        "@id": f"{product_url(product)}#product",
        "name": name,
        "description": product_description(product),
        "image": images,
        "sku": str(product.get("item_id", "")),
        "category": CATEGORY_LABELS.get(compact_text(product.get("store_category")), "Reptile shop product"),
        "brand": {"@type": "Brand", "name": BUSINESS_NAME},
        "url": product_url(product),
    }
    try:
        price = float(product.get("price") or 0)
    except (TypeError, ValueError):
        price = 0
    if price > 0:
        offer: dict[str, Any] = {
            "@type": "Offer",
            "url": product_url(product),
            "priceCurrency": "USD",
            "price": f"{price:.2f}",
            "availability": availability_schema(product),
            "itemCondition": "https://schema.org/NewCondition",
            "seller": {"@id": f"{BASE_URL}/#business"},
        }
        if product.get("local_pickup_only"):
            offer["availableDeliveryMethod"] = "https://purl.org/goodrelations/v1#DeliveryModePickUp"
            offer["areaServed"] = {"@type": "State", "name": "Colorado"}
        data["offers"] = offer
    return data


