def breadcrumb_schema(items: list[tuple[str, str]]) -> dict[str, Any]:
    return {
        "@type": "BreadcrumbList",
        "itemListElement": [
            {"@type": "ListItem", "position": index, "name": name, "item": url}
            for index, (name, url) in enumerate(items, start=1)
        ],
    }


def breadcrumb_html(items: list[tuple[str, str]]) -> str:
    links = []
    for index, (name, url) in enumerate(items):
        if index == len(items) - 1:
            links.append(f"<span aria-current=\"page\">{escape(name)}</span>")
        else:
            links.append(f"<a href=\"{escape(url)}\">{escape(name)}</a>")
    return '<nav class="breadcrumbs" aria-label="Breadcrumb">' + " <span aria-hidden=\"true\">/</span> ".join(links) + "</nav>"


