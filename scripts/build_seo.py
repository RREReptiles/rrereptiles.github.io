def escape(value: Any) -> str:
    return html.escape(str(value or ""), quote=True)


def compact_text(value: Any, fallback: str = "") -> str:
    text = re.sub(r"\s+", " ", str(value or "")).strip()
    return text or fallback


def json_script(data: Any) -> str:
    payload = json.dumps(data, ensure_ascii=False, separators=(",", ":"))
    return payload.replace("</", "<\\/")


def absolute_url(value: str | None) -> str:
    if not value:
        return DEFAULT_IMAGE
    value = value.strip()
    if value.startswith("https://") or value.startswith("http://"):
        return value
    return f"{BASE_URL}/{value.lstrip('/')}"


def read_storefront_config() -> tuple[str, str]:
    text = STOREFRONT_JS_PATH.read_text(encoding="utf-8")
    url_match = re.search(r"const SUPABASE_URL = '([^']+)'", text)
    key_match = re.search(r"const SUPABASE_PUBLISHABLE_KEY = '([^']+)'", text)
    if not url_match or not key_match:
        raise RuntimeError("Could not read the public Supabase storefront configuration.")
    return url_match.group(1), key_match.group(1)


def fetch_catalog(fixture: Path | None = None) -> list[dict[str, Any]]:
    if fixture:
        payload = json.loads(fixture.read_text(encoding="utf-8"))
        if isinstance(payload, dict):
            payload = payload.get("products", [])
        if not isinstance(payload, list):
            raise RuntimeError("Catalog fixture must be a JSON array or contain a products array.")
        return [dict(row) for row in payload]

    supabase_url, publishable_key = read_storefront_config()
    request = urllib.request.Request(
        f"{supabase_url}/rest/v1/rpc/get_storefront_catalog",
        data=b"{}",
        method="POST",
        headers={
            "apikey": publishable_key,
            "Authorization": f"Bearer {publishable_key}",
            "Content-Type": "application/json",
            "User-Agent": "RRE-SEO-Generator/1.0",
        },
    )
    try:
        with urllib.request.urlopen(request, timeout=30) as response:
            payload = json.load(response)
    except (urllib.error.URLError, TimeoutError, json.JSONDecodeError) as error:
        raise RuntimeError(f"Could not load the public storefront catalog: {error}") from error
    if not isinstance(payload, list):
        raise RuntimeError("The storefront catalog response was not a JSON array.")
    return [dict(row) for row in payload]


