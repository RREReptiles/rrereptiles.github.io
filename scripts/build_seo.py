def extract_tag(text: str, tag: str, class_name: str | None = None) -> str:
    class_part = rf'[^>]*class="[^"]*\b{re.escape(class_name)}\b[^"]*"[^>]*' if class_name else "[^>]*"
    match = re.search(rf"<{tag}{class_part}>(.*?)</{tag}>", text, flags=re.IGNORECASE | re.DOTALL)
    return compact_text(re.sub(r"<[^>]+>", " ", html.unescape(match.group(1)))) if match else ""


